CREATE TABLE IF NOT EXISTS perfil (
  PERFIL_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  PERFIL_NOMBRE VARCHAR(50) NOT NULL,
  ACTIVO TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS usuarios (
  USUARIOS_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USUARIOS_NOMBRE VARCHAR(80) NOT NULL,
  USUARIOS_APELLIDO VARCHAR(80) NOT NULL DEFAULT '',
  USUARIOS_DNI VARCHAR(30) NULL,
  USUARIOS_EMAIL VARCHAR(150) NOT NULL,
  USUARIOS_TELEFONO VARCHAR(30) NULL,
  USUARIOS_PASSWORD VARCHAR(255) NOT NULL,
  PERFIL_ID INT UNSIGNED NOT NULL DEFAULT 5,
  DUENO_ID INT UNSIGNED NULL,
  ACTIVO TINYINT(1) NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS provincia (
  PROVINCIA_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  PROVINCIA_NOMBRE VARCHAR(80) NOT NULL,
  ACTIVO TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS partido (
  PARTIDO_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  PARTIDO_NOMBRE VARCHAR(80) NOT NULL,
  PROVINCIA_ID INT UNSIGNED NOT NULL,
  ACTIVO TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS localidad (
  LOCALIDAD_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  LOCALIDAD_NOMBRE VARCHAR(80) NOT NULL,
